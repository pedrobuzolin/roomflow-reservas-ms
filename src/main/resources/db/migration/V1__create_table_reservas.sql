CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE reservas
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_reserva VARCHAR(100) NOT NULL,
    data_inicio    TIMESTAMP    NOT NULL,
    data_fim       TIMESTAMP    NOT NULL,
    sala_id        BIGINT       NOT NULL,
    usuario_id     BIGINT       NOT NULL,

    CONSTRAINT reservas_periodo_valido
        CHECK (data_inicio < data_fim),

    CONSTRAINT reservas_status_valido
        CHECK (status_reserva IN ('ATIVA', 'CANCELADA')),

    CONSTRAINT reservas_sem_sobreposicao
        EXCLUDE USING gist (
        sala_id WITH =,
        tsrange(data_inicio, data_fim, '[)') WITH &&
        )
        WHERE (status_reserva = 'ATIVA')
);

CREATE INDEX idx_reservas_usuario_id ON reservas (usuario_id);